    function getStatusMeta(status, timing) {
      const label = timing
        ? (timing.exact ? "" : "~") + formatDuration(clock.now() - timing.start)
        : "";
      switch (status) {
        case "in_progress":
          return {
            key: "in_progress",
            label: "In Progress",
            timerHtml: timing ? ` <span class="row-timer-sec">${label}</span>` : "",
            class: "st-in-progress" + (timing ? " has-timer" : "")
          };
        case "deploying":
          return {
            key: "deploying",
            label: "Deploying…",
            timerHtml: timing ? ` <span class="row-timer-sec">${label}</span>` : "",
            class: "st-deploying" + (timing ? " has-timer" : "")
          };
        case "deployed":
          return { key: "deployed", label: "Deployed", timerHtml: "", class: "st-deployed" };
        case "resolved":
          return { key: "resolved", label: "Resolved", timerHtml: "", class: "st-resolved" };
        case "open":
        default:
          return { key: "open", label: "Open", timerHtml: "", class: "st-open" };
      }
    }

