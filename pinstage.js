    ["pushState", "replaceState"].forEach((fn) => {
      const orig = history[fn];
      history[fn] = function () {
        const r = orig.apply(this, arguments);
        setTimeout(onPathMaybeChanged, 0);
        return r;
      };
    });
    addEventListener("popstate", onPathMaybeChanged);

