    function startRealtimeSync() {
      if (syncTimer) clearInterval(syncTimer);
      syncTimer = setInterval(syncRealtime, 1500);
      addEventListener("focus", syncRealtime);
      document.addEventListener("visibilitychange", () => {
        if (!document.hidden) syncRealtime();
      });
    }

    let badgeTickerTimer = null;
    const RING_CIRCUMFERENCE = 44; // matches the <circle> stroke-dasharray

    function updateBadgeProgress(badgeEl, timing) {
      if (!badgeEl || !timing) return;
      const elapsedMs = Math.max(0, clock.now() - timing.start);
      const elapsed = (timing.exact ? "" : "~") + formatDuration(elapsedMs);
      const timerSec = badgeEl.querySelector(".timer-sec");
      if (timerSec) timerSec.textContent = elapsed;

      const phaseLabel =
        timing.phase === "deploy" ? "Deploying fix to staging" : "Autonomous fix in progress";
      const typical = typicalDurationMs(timing.phase);
      const ringFg = badgeEl.querySelector(".ring-fg");
      let title = phaseLabel + " · " + elapsed + " elapsed";

      if (typical) {
        // A real fraction of a measured median. It stops at 92% rather than
        // creeping toward 100%: once a run passes the typical duration, all
        // anyone actually knows is that it is longer than usual, and the
        // honest way to say that is to stop moving.
        const frac = Math.min(0.92, Math.max(0.04, elapsedMs / typical));
        badgeEl.classList.remove("is-indeterminate");
        if (ringFg)
          ringFg.setAttribute("stroke-dashoffset", (RING_CIRCUMFERENCE * (1 - frac)).toFixed(1));
        title += " · usually " + formatDuration(typical);
      } else {
        // Nothing has finished on this project yet, so there is no
        // denominator. Spin to show that work is happening instead of
        // inventing a percentage of a number nobody measured.
        badgeEl.classList.add("is-indeterminate");
        if (ringFg)
          ringFg.setAttribute("stroke-dashoffset", (RING_CIRCUMFERENCE * 0.72).toFixed(1));
      }
      if (!timing.exact) title += " (approximate — claimed before start times were recorded)";
      badgeEl.title = title;
    }

