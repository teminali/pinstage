  /* ── clock ────────────────────────────────────────────────────────────
   * Every `_ts` on a thread is written by whichever machine changed it — a
   * teammate's browser, or the MCP server on a developer's laptop — and read
   * back on a different machine again. Two clocks that disagree by a minute
   * (a laptop that slept since yesterday, a VM that never ran NTP) turn "how
   * long has this fix been running" into fiction, and the `Math.max(0, …)`
   * around the subtraction hides the negative half of that error as a
   * permanent, plausible-looking "0s".
   *
   * So nothing here stamps or reads a raw local clock. Every REST response
   * carries a `Date` header generated by the SERVER — the one timeline all
   * writers and readers already share. Sample the offset against it, keep the
   * sample from the shortest round-trip (least transport error, the same
   * reason NTP prefers its shortest exchange), and put every timestamp
   * through it. `Date` is whole-second, so each sample is uncertain by up to
   * a second: immaterial to a readout that counts in seconds, and orders of
   * magnitude better than an uncorrected clock.
   */
  const clock = {
    offset: 0, // serverNow - Date.now()
    rtt: Infinity, // round-trip of the sample `offset` came from
    at: 0, // when that sample was taken (local ms)
    calibrated: false,
    observe(header, sentAt, gotAt) {
      const server = Date.parse(header || "");
      if (!Number.isFinite(server)) return;
      const rtt = gotAt - sentAt;
      // A new sample wins on transport error; any sample wins once the stored
      // one is 5 minutes old, otherwise one lucky early exchange pins the
      // offset for the session and a drifting clock is never re-corrected.
      if (rtt > this.rtt && gotAt - this.at < 300000) return;
      // The header is truncated to the second, so the instant it names is
      // uniformly distributed over the second that follows: +500ms is its
      // mean. The request was served near the local midpoint of the exchange.
      this.offset = server + 500 - (sentAt + gotAt) / 2;
      this.rtt = rtt;
      this.at = gotAt;
      this.calibrated = true;
    },
    now() {
      return Date.now() + this.offset;
    },
  };

