    /* ── elapsed-time model ───────────────────────────────────────────────
     * "How long has this been worked on" is a MEASUREMENT, and a measurement
     * needs an anchor that does not move. The old readout had none. It
     * reached first for `claimedBy.claimedAt`, which nothing has ever
     * written; fell through to `lastActivityAt`, which is bumped by every
     * reply and every status change, so the timer restarted at zero each time
     * the agent posted a progress note; then to `createdAt`, which measures
     * time since the issue was REPORTED, not since work began — hours out on
     * anything triaged the next morning; and finally to `Date.now()`, which
     * renders a confident "0s" for a thread whose start is simply unknown.
     * Four fallbacks, three of them wrong, none of them distinguishable on
     * screen from a real number.
     *
     * The anchors below are stamped once, by the transition that actually
     * starts the phase, and are never moved again.
     */
    const WORKING_STATUSES = { in_progress: 1, deploying: 1 };

    /**
     * The instant the CURRENT phase began, or null when the thread is not
     * being worked on. `exact: false` marks a pre-anchor thread whose start
     * had to be inferred — shown with a "~" rather than passed off as
     * measured.
     */
    function phaseTiming(d) {
      const st = (d && d.status) || "open";
      if (!WORKING_STATUSES[st]) return null;
      const phase = st === "deploying" ? "deploy" : "fix";
      const stamped =
        st === "deploying"
          ? (d.deployStartedAt && d.deployStartedAt._ts) || (d.workStartedAt && d.workStartedAt._ts)
          : d.workStartedAt && d.workStartedAt._ts;
      if (stamped) return { start: stamped, exact: true, phase };
      // Threads claimed before this build carry no phase anchor. A claim
      // timestamp is a faithful stand-in; `lastActivityAt` is only a lower
      // bound, so it is labelled approximate instead of being dressed up as a
      // measurement.
      const claimed = (d.claimedBy && ((d.claimedBy.at && d.claimedBy.at._ts) || (d.claimedBy.claimedAt && d.claimedBy.claimedAt._ts)));
      if (claimed) return { start: claimed, exact: true, phase };
      const loose = d.lastActivityAt && d.lastActivityAt._ts;
      if (loose) return { start: loose, exact: false, phase };
      return null;
    }

    /** Markup attributes a live ticker needs to keep counting a rendered badge. */
    const timingAttrs = (timing) =>
      timing ? ` data-start-time="${timing.start}" data-exact="${timing.exact ? 1 : 0}"` : "";

    /**
     * The single place a thread's status and its timing stamps change
     * together, so the two can never disagree. The MCP server carries a
     * deliberate twin of this function (mcp/pinstage-mcp.mjs) — change one,
     * change the other.
     */
    function applyStatusTransition(data, status, actor) {
      const t = now();
      data.status = status;
      data.lastActivityAt = t;

      if (WORKING_STATUSES[status]) {
        // Stamped ONCE, and never again while work continues: this is the
        // whole fix. in_progress -> deploying keeps the same `workStartedAt`,
        // so the total stays honest across the phase change.
        if (!data.workStartedAt) data.workStartedAt = t;
        if (status === "deploying") {
          if (!data.deployStartedAt) data.deployStartedAt = t;
        } else {
          // Back to coding after a deploy: that deploy's measurement is over.
          if (data.deployStartedAt && !data.deployEndedAt) data.deployEndedAt = t;
        }
        if (!data.claimedBy || data.claimedBy.uid !== actor.uid) {
          data.claimedBy = { uid: actor.uid, name: actor.name, author: actor.name, at: t };
        }
        delete data.workEndedAt;
      } else {
        // Leaving the working phases closes whatever is still open, which is
        // what makes a completed run measurable after the fact.
        if (data.deployStartedAt && !data.deployEndedAt) data.deployEndedAt = t;
        if (data.workStartedAt && !data.workEndedAt) data.workEndedAt = t;
      }

      if (status === "open") {
        // A reset means nobody is on this any more, so the part-finished
        // measurement is void — drop it rather than let the next claim resume
        // someone else's clock.
        delete data.workStartedAt;
        delete data.workEndedAt;
        delete data.deployStartedAt;
        delete data.deployEndedAt;
        delete data.claimedBy;
      }
      return data;
    }

    /* ── how long these normally take, measured ───────────────────────────
     * The ring used to fill against a hardcoded 45s (95s deploying) and then
     * creep asymptotically to 95% forever, so a ten-minute fix spent nine of
     * them sitting at "nearly done". A percentage needs a denominator that
     * came from somewhere: these are the durations of runs that actually
     * finished on this project, harvested from the threads as they are read.
     */
    const DURATION_KEY = "pinstage:durations:" + project;
    const DURATION_KEEP = 24;

    function loadDurations() {
      try {
        const raw = JSON.parse(localStorage.getItem(DURATION_KEY) || "{}");
        return { fix: raw.fix || {}, deploy: raw.deploy || {} };
      } catch (e) {
        return { fix: {}, deploy: {} };
      }
    }

    /** Record every completed run these rows can prove. Keyed by thread id, so
     *  re-reading the same rows on the next poll cannot inflate the sample. */
    function harvestDurations(list) {
      if (!Array.isArray(list) || !list.length) return;
      const store = loadDurations();
      let added = 0;
      list.forEach((row) => {
        const d = (row && row.data) || {};
        const pairs = [
          ["fix", d.workStartedAt, d.workEndedAt],
          ["deploy", d.deployStartedAt, d.deployEndedAt],
        ];
        pairs.forEach(([phase, a, b]) => {
          if (!a || !b || !a._ts || !b._ts) return;
          const ms = b._ts - a._ts;
          // A run that measures as negative or as most of a day is a clock
          // that moved or a thread someone left claimed overnight; either way
          // it is not evidence about how long this work takes.
          if (ms <= 0 || ms > 6 * 3600 * 1000) return;
          if (store[phase][row.id] === ms) return;
          store[phase][row.id] = ms;
          added++;
        });
      });
      if (!added) return;
      ["fix", "deploy"].forEach((phase) => {
        const keys = Object.keys(store[phase]);
        if (keys.length > DURATION_KEEP) {
          keys.slice(0, keys.length - DURATION_KEEP).forEach((k) => delete store[phase][k]);
        }
      });
      try {
        localStorage.setItem(DURATION_KEY, JSON.stringify(store));
      } catch (e) {
        /* private mode, quota — the ring just stays indeterminate */
      }
    }

    /** Median past duration for a phase, or null while there is no basis for
     *  a percentage. Median, not mean: one thread left claimed over lunch
     *  should not move the denominator. */
    function typicalDurationMs(phase) {
      const store = loadDurations();
      const xs = Object.values(store[phase] || {}).sort((a, b) => a - b);
      if (xs.length < 3) return null;
      const mid = xs.length >> 1;
      return xs.length % 2 ? xs[mid] : Math.round((xs[mid - 1] + xs[mid]) / 2);
    }

